// Day 2: Demonstrates basic C++ data types (int, float, char, string)
#include <iostream>
#include <string>

int main() {
    // Integer
    int age = 25;
    // Floating point number
    float pi = 3.14159f;
    // Character
    char grade = 'A';
    // String
    std::string greeting = "Hello";

    std::cout << "Age: " << age << "\n";
    std::cout << "Pi: " << pi << "\n";
    std::cout << "Grade: " << grade << "\n";
    std::cout << "Greeting: " << greeting << "\n";

    return 0;
}
